export type FlowNode = '需求' | '实现' | '检查' | '记录' | '归档' | '收件箱';

const STATUS_TO_NODE: Record<string, FlowNode> = {
  new: '需求',
  ready: '实现',
  review: '检查',
  done: '归档',
  recorded: '归档',
  need_human: '收件箱',
};

export function mapStatusToNode(status: string): FlowNode {
  // 未知/空状态统一降级收件箱（清单位，不占画布），不抛异常
  return STATUS_TO_NODE[status] ?? '收件箱';
}
